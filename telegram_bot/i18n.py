def t(key: str, lang: str = "uk", **kw) -> str:
    src = EN if lang == "en" else UK
    text = src.get(key) or UK.get(key, key)
    # Auto-fill common placeholders so handlers don't need to pass site/channel
    # values for every translation call.
    try:
        from . import config as _cfg
        defaults = {
            "site": _cfg.SITE_URL,
            "channel": _cfg.TG_CHANNEL_USERNAME,
            "channel_url": _cfg.TG_CHANNEL_URL,
        }
    except Exception:
        defaults = {
            "site": "https://picksy.my",
            "channel": "@itspicksy",
            "channel_url": "https://t.me/itspicksy",
        }
    merged = {**defaults, **kw}
    try:
        return text.format(**merged)
    except Exception:
        return text
